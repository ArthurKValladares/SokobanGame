def solid_material(name, color, roughness=.88, metallic=0):
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    bsdf = next(n for n in material.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
    bsdf.inputs['Base Color'].default_value = (*color, 1)
    bsdf.inputs['Roughness'].default_value = roughness
    bsdf.inputs['Metallic'].default_value = metallic
    material.diffuse_color = (*color, 1)
    return material


def grain_material():
    """Eight padded painted wood swatches; long grain and restrained knots."""
    width, height, band = 1024, 512, 64
    pixels = np.empty((height, width, 4), dtype=np.float32)
    x = np.arange(width, dtype=np.float32)[None, :] / width
    v = np.arange(band, dtype=np.float32)[:, None] / band
    # Medium, desaturated brown remains legible in the game's blue-violet
    # wall shadows. Dark grooves, cooler wear and pale fracture grain retain
    # the old weathered wood rather than fresh orange lumber.
    bases = [(133, 101, 73), (148, 113, 81), (122, 92, 66), (139, 105, 76),
             (156, 120, 86), (129, 102, 77), (144, 117, 91), (181, 142, 103)]
    for row, base in enumerate(bases):
        rng = np.random.default_rng(19815 + row)
        # Broad, soft streaks carry the painted style at tile-camera distances.
        warp = v + .021 * np.sin(x * 17 + row * 1.8) + .012 * np.sin(x * 33 + v * 5)
        grain = (4.6 * np.sin(warp * 23 + row * 1.3) + 3.1 * np.sin(warp * 64 + row) + 2.0 * np.sin(warp * 137 + x * 9)
                 + 1.3 * np.sin(warp * 241 + x * 13))
        shade = grain + 3 * (v - .5) + rng.normal(0, 1.0, (band, width))
        for index in range(7):
            center = .12 + index * .116 + .015 * np.sin(x * (9 + index) + row + index)
            width_line = .004 + .003 * (index % 3)
            groove = np.exp(-((v - center) / width_line) ** 2)
            fade = .55 + .45 * np.sin(x * 6 + index) ** 2
            shade -= groove * fade * (11 if index % 3 else 17)
            shade += np.exp(-((v - center - .012) / .009) ** 2) * 5
        if row != 7:
            # Elliptical ring knots align with the rail's long axis.
            cx, cy = .20 + .095 * (row % 5), .44 + .10 * (row % 2)
            radius = np.sqrt(((x - cx) / .052) ** 2 + ((v - cy) / .16) ** 2)
            shade -= np.exp(-(radius / .44) ** 2) * 24
            shade -= np.exp(-((radius - 1.02) / .10) ** 2) * 11
            shade += np.exp(-((radius - 1.16) / .12) ** 2) * 7
        else:
            # Pale end-grain is reserved for genuine fractured/end faces.
            shade += 5 * np.sin(np.sqrt(((x-.5)*5)**2 + ((v-.5)*2)**2) * 27)
        rgb = np.clip(np.array(base)[None, None, :] + shade[:, :, None], 0, 255) / 255
        # A generated byte image stores these sRGB paint values directly.
        # Do not linearize here: glTF sampling converts the encoded PNG once.
        pixels[row*band:(row+1)*band, :, :3] = rgb
        pixels[row*band:(row+1)*band, :, 3] = 1
    image = bpy.data.images.new('Fence | weathered walnut painted grain', width=width, height=height, alpha=False)
    image.pixels.foreach_set(pixels.reshape(-1))
    image.filepath_raw = str(KIT / 'fence_weathered_wood.png')
    image.file_format = 'PNG'
    image.save()
    # Reopen the encoded PNG so the source renderer and glTF export sample
    # precisely the same sRGB texture, including Blender's color management.
    bpy.data.images.remove(image)
    image=bpy.data.images.load(str(KIT / 'fence_weathered_wood.png'),check_existing=False)
    image.name='Fence | weathered walnut painted grain'
    image.pack()
    material = solid_material('Fence weathered dark wood | painted grain', (.2,.12,.07), .91)
    bsdf = next(n for n in material.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
    tex = material.node_tree.nodes.new('ShaderNodeTexImage')
    tex.image = image
    tex.interpolation = 'Linear'
    material.node_tree.links.new(tex.outputs['Color'], bsdf.inputs['Base Color'])
    return material


wood = grain_material()
iron = solid_material('Fence aged forged iron | nail heads and collars', (.075,.085,.079), .72, .45)
MATERIALS = [wood, iron]
RAIL_COUNT = 4
RAIL_HEIGHT = .115
RAIL_DEPTH = .05
RAIL_CENTERS = tuple(.1775 + row * .195 for row in range(RAIL_COUNT))


class Builder:
    def __init__(self):
        self.vertices, self.faces, self.uvs, self.materials = [], [], [], []

    def island(self, vertices, faces, uvs, material=0):
        offset = len(self.vertices)
        self.vertices.extend(vertices)
        self.faces.extend(tuple(offset + v for v in f) for f in faces)
        self.uvs.extend(uvs)
        self.materials.extend([material] * len(faces))

    def object(self, name):
        mesh = bpy.data.meshes.new(name + ' | editable closed timber islands')
        mesh.from_pydata(self.vertices, [], self.faces)
        for material in MATERIALS:
            mesh.materials.append(material)
        mesh.update()
        bm = bmesh.new()
        bm.from_mesh(mesh)
        bmesh.ops.recalc_face_normals(bm, faces=list(bm.faces))
        bm.to_mesh(mesh)
        bm.free()
        # Face order is unchanged by normal recalculation. UVs are assigned by
        # vertex identity because recalc may reverse a face's loop order.
        layer = mesh.uv_layers.new(name='Painted grain UV')
        for polygon, face, mapping, material in zip(mesh.polygons, self.faces, self.uvs, self.materials):
            polygon.material_index = material
            lookup = dict(zip(face, mapping))
            for loop in polygon.loop_indices:
                layer.data[loop].uv = lookup[mesh.loops[loop].vertex_index]
        obj = bpy.data.objects.new(name, mesh)
        catalog.objects.link(obj)
        return obj


def swatch_uv(u, v, swatch):
    # A wide gutter keeps tiny mip levels safely inside each grain swatch.
    return (.035 + .93 * u, (swatch + .16 + .68 * v) / 8)


def octagon(a, b, bevel):
    return [(-a+bevel,-b), (a-bevel,-b), (a,-b+bevel), (a,b-bevel),
            (a-bevel,b), (-a+bevel,b), (-a,b-bevel), (-a,-b+bevel)]


def rail(builder, row, variant, x0=-.5, x1=.5, fracture0=False, fracture1=False):
    center = RAIL_CENTERS[row]
    height, depth, bevel = RAIL_HEIGHT, RAIL_DEPTH, .007
    a,b=depth/2,height/2
    # Extra collinear corners in each broad face allow genuine pointed and
    # notched fracture silhouettes, rather than a single clean diagonal cut.
    cross=[(-a+bevel,-b),(a-bevel,-b),(a,-b+bevel),
           (a,-height*.25),(a,-height*.07),(a,height*.12),(a,height*.29),(a,b-bevel),
           (a-bevel,b),(-a+bevel,b),(-a,b-bevel),
           (-a,height*.29),(-a,height*.12),(-a,-height*.07),(-a,-height*.25),(-a,-b+bevel)]
    count=len(cross)

    def fracture(cz):
        knots=[(-b,-.008),(-b+bevel,.012),(-height*.25,.057),(-height*.07,-.017),
               (height*.12,.034),(height*.29,-.012),(b-bevel,.026),(b,.009)]
        for (za,xa),(zb,xb) in zip(knots,knots[1:]):
            if za<=cz<=zb:
                return xa+(xb-xa)*(cz-za)/(zb-za)
        return 0
    # Outer rows preserve the module's canonical .12/.82 limits. The two
    # inner rows sag, twist and lean more in the crooked/damaged variants.
    tilt = 0 if row in (0,RAIL_COUNT-1) else {1:.006, 2:.025, 3:.018, 4:.022}[variant] * (-1 if row % 2 else 1)
    bow = {1:.004,2:.010,3:.008,4:.012}[variant] * (-1 if row == RAIL_COUNT-1 else 1)
    if row == 0:
        bow = abs(bow)
    samples = 8
    vertices = []
    uv_by_vertex = []
    swatch = (row + variant * 2) % 7
    for index in range(samples + 1):
        t = index / samples
        x = x0 + (x1-x0)*t
        full_t = x + .5
        z = center + tilt * (full_t-.5) + bow * math.sin(full_t * math.pi)
        y = .0017 * math.sin(full_t * math.tau + row * 1.4 + variant)
        for corner, (cy, cz) in enumerate(cross):
            xx = x
            if index == 0 and fracture0:
                xx -= fracture(cz)
            if index == samples and fracture1:
                xx += fracture(cz)
            vertices.append((xx,y+cy,z+cz))
            uv_by_vertex.append(swatch_uv(full_t, cz / height + .5, swatch))
    faces, uvs = [], []
    for index in range(samples):
        for corner in range(count):
            face = (index*count+corner, index*count+(corner+1)%count,
                    (index+1)*count+(corner+1)%count, (index+1)*count+corner)
            faces.append(face)
            uvs.append([uv_by_vertex[v] for v in face])
    for end in (0, samples):
        # Fan caps follow every jagged end vertex; no open fracture polygons.
        c = tuple(sum(vertices[end*count+j][axis] for j in range(count))/count for axis in range(3))
        idx = len(vertices)
        vertices.append(c)
        for corner in range(count):
            face = (idx, end*count+corner, end*count+(corner+1)%count)
            faces.append(face)
            uvs.append([swatch_uv(.5,.5,7), swatch_uv(.25+corner/(2*count),.25,7),
                        swatch_uv(.25+(corner+1)/(2*count),.75,7)])
    builder.island(vertices, faces, uvs)


def make_slats(variant):
    builder = Builder()
    for row in range(RAIL_COUNT):
        if variant == 3 and row == 2:
            continue
        if variant == 4 and row in (1,2):
            gap = (-.11,.16) if row == 1 else (-.24,.09)
            rail(builder,row,variant,x1=gap[0],fracture1=True)
            rail(builder,row,variant,x0=gap[1],fracture0=True)
        else:
            rail(builder,row,variant)
    return builder.object(f'TileDecorationFenceSlats{variant:02}')


def post_center(z, variant):
    lean = [0,.003,-.005,.007,.004][variant]
    return (lean * math.sin(z / .95 * math.pi), .002 * math.sin(z * 7 + variant) * math.sin(z / .95 * math.pi))


def vertical_timber(builder, rings, variant, material=0):
    vertices, faces, uvs = [], [], []
    for z, radius in rings:
        cx, cy = post_center(z,variant)
        for i,(x,y) in enumerate(octagon(radius,radius,.008)):
            zz = z
            if z == .95 and variant in (2,3,4):
                zz -= ([.025,.008,0,.013,.037,.024,.008,.019][i] if variant == 4
                       else [.007,0,.004,.012,.006,.002,.009,.013][(i+variant)%8])
            vertices.append((cx+x,cy+y,zz))
    for ring in range(len(rings)-1):
        z0,z1 = rings[ring][0],rings[ring+1][0]
        for i in range(8):
            face=(ring*8+i,ring*8+(i+1)%8,(ring+1)*8+(i+1)%8,(ring+1)*8+i)
            faces.append(face)
            # Rotate grain along the post; four faces show different streaks.
            uvs.append([swatch_uv(z0/.95,.18,i%7),swatch_uv(z0/.95,.82,i%7),
                        swatch_uv(z1/.95,.82,i%7),swatch_uv(z1/.95,.18,i%7)])
    for ring in (0,len(rings)-1):
        face=tuple(ring*8+i for i in range(8))
        faces.append(face)
        uvs.append([swatch_uv(.5+.3*math.cos(i*math.tau/8),.5+.3*math.sin(i*math.tau/8),7) for i in range(8)])
    builder.island(vertices,faces,uvs,material)


def nail(builder,z,variant,side):
    cx,cy=post_center(z,variant)
    radius=.0065
    vertices=[]
    for y,scale in ((side*.041,1),(side*.048,1),(side*.05,.70)):
        for i in range(6):
            angle=i*math.tau/6+.2
            vertices.append((cx+radius*scale*math.cos(angle),cy+y,z+radius*scale*math.sin(angle)))
    faces=[tuple(range(6)),tuple(range(12,18))]
    for ring in range(2):
        for i in range(6):
            faces.append((ring*6+i,ring*6+(i+1)%6,(ring+1)*6+(i+1)%6,(ring+1)*6+i))
    builder.island(vertices,faces,[[(0,0)]*len(face) for face in faces],1)


def make_post(variant):
    builder=Builder()
    # A stout, hand-cut octagonal post, tapered and lightly uneven at its head.
    radii={1:[.039,.041,.039,.040,.040,.038,.033],
           2:[.041,.042,.039,.038,.040,.037,.032],
           3:[.039,.040,.038,.037,.038,.036,.031],
           4:[.040,.042,.039,.040,.039,.036,.030]}[variant]
    heights=[0,.065,.25,.47,.72,.89,.95]
    vertical_timber(builder,list(zip(heights,radii)),variant)
    for z in (.13,.805):
        # Very thin square forged collars catch the light without dominating.
        vertical_timber(builder,[(z-.012,.043),(z+.012,.043)],variant,1)
    for z in RAIL_CENTERS:
        for side in (-1,1):
            nail(builder,z,variant,side)
    return builder.object(f'TileDecorationFencePost{variant:02}')


